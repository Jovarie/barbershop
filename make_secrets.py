"""Build the git-ignored settings files for Google Cloud from .env, so values are
never retyped by hand.

Run before each deploy:  python make_secrets.py
  secrets.yaml                      -> the Flask app on App Engine
  functions/booking-email.env.yaml  -> the booking-email cloud function
  functions/send-reminders.env.yaml -> the send-reminders cloud function
None of these files are committed; they are only ever uploaded to Google.
"""
import json
import secrets

from dotenv import dotenv_values

APP = ["DATABASE_URL", "MONGODB_URI", "FIREBASE_API_KEY", "FIREBASE_AUTH_DOMAIN",
       "FIREBASE_PROJECT_ID", "FIREBASE_APP_ID", "ADMIN_EMAILS", "FUNCTION_SECRET"]
BOOKING_EMAIL = ["BREVO_API_KEY", "SENDER_EMAIL", "FUNCTION_SECRET"]
SEND_REMINDERS = ["DATABASE_URL", "FUNCTION_SECRET", "EMAIL_FUNCTION_URL"]

env = dotenv_values(".env")


def write(path, names, top_key=None, extra=None):
    values = {name: env.get(name) or "" for name in names}
    values.update(extra or {})
    indent = "  " if top_key else ""
    lines = ["# Generated by make_secrets.py from .env. Git-ignored: never commit this file."]
    if top_key:
        lines.append(f"{top_key}:")
    lines += [f"{indent}{name}: {json.dumps(value)}" for name, value in values.items()]
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    missing = [name for name in names if not env.get(name)]
    print(f"{path} written." + (f" MISSING from .env: {', '.join(missing)}" if missing else ""))


# App Engine: a fresh, long random SECRET_KEY for production (different from the one on
# my Mac). COOKIE_SECURE is left out on purpose, so cookies are only sent over HTTPS.
# EMAIL_FUNCTION_URL is only added once the booking-email function has been deployed.
app_extra = {"SECRET_KEY": secrets.token_urlsafe(48)}
if env.get("EMAIL_FUNCTION_URL"):
    app_extra["EMAIL_FUNCTION_URL"] = env["EMAIL_FUNCTION_URL"]
write("secrets.yaml", APP, top_key="env_variables", extra=app_extra)

# Cloud functions: gcloud's --env-vars-file wants plain NAME: value lines.
write("functions/booking-email.env.yaml", BOOKING_EMAIL)
write("functions/send-reminders.env.yaml", SEND_REMINDERS)
